/**
 * Порядок карточек каталога — общий для киоска и админки.
 *
 * Держится здесь, а не в киоске: окно «Обкладинки груп» показывает тот же список,
 * что видит покупатель, и перетаскивание в нём было бы бессмысленным, если бы на
 * экране прибора группы стояли иначе.
 */
import type { Category, Product } from './types'

/**
 * Группы в том порядке, в каком их показывать.
 *
 * Пока порядок не задан руками, список переворачивается: API отдаёт группы по
 * алфавиту, а на экране первой должна стоять последняя — так попросил владелец.
 * Как только оператор перетащил группы в админке, переворачивать нечего: заданный
 * порядок и есть порядок, а спорить с ним — показывать оператору не то, что он
 * только что собрал. Бэкенд к этому моменту уже отсортировал список по `sort_order`.
 */
export function orderedCategories(categories: Category[]): Category[] {
  const arranged = categories.some((category) => category.sort_order !== null)
  return arranged ? [...categories] : [...categories].reverse()
}

/** Товары: порядок задаёт только код (API отдаёт по возрастанию), и он переворачивается. */
export function orderedProducts(products: Product[]): Product[] {
  return [...products].reverse()
}
